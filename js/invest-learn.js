export function learnCard() {
  const read = new Set(store.prefs.invLearned || []);
  const n = LESSONS.filter(l => read.has(l.id)).length;
  const next = LESSONS.find(l => !read.has(l.id));
  return `<div class="card inv-learn">
    <div class="row" style="margin-bottom:6px"><h2 style="margin:0">📚 投資入門</h2><span class="spacer"></span>
      <span class="sub">已讀 ${n} / ${LESSONS.length}</span></div>
    <div class="progress thin" style="margin-bottom:8px;max-width:none"><div style="width:${Math.round(n / LESSONS.length * 100)}%;background:var(--accent)"></div></div>
    ${next ? `<div class="sub" style="margin-bottom:6px">下一課：${next.icon} ${next.title}</div>` : '<div class="sub" style="margin-bottom:6px">全部讀完了 🎉 有空可以再複習。</div>'}
    ${LESSONS.map(l => `<details class="lesson ${read.has(l.id) ? 'read' : ''}">
      <summary><span>${l.icon}</span><span class="lesson-title">${l.title}</span>${read.has(l.id) ? '<span class="lesson-ok">✓</span>' : ''}</summary>
      <div class="md">${mdLite(l.body)}</div>
      <div class="row" style="margin-top:8px"><span class="spacer"></span>
        <button class="btn small ${read.has(l.id) ? '' : 'primary'}" data-action="inv-learn" data-id="${l.id}">${read.has(l.id) ? '標成沒讀' : '✓ 讀完了'}</button></div>
    </details>`).join('')}
  </div>`;
}

export const learnActions = {
  'inv-learn': el => {
    const read = new Set(store.prefs.invLearned || []);
    if (read.has(el.dataset.id)) read.delete(el.dataset.id); else read.add(el.dataset.id);
    savePrefs({ invLearned: [...read] });
  },
};
